"""Chronological-day evaluation for files containing actual and replay predictions.

Input columns: date, actual_wait_min, people_ahead, fifo_prediction_min.
The FIFO prediction must be generated by a faithful state replay before evaluation.
"""
import argparse, csv, math, json
from collections import defaultdict
from pathlib import Path


def split_days(rows, train_fraction=0.7):
    days = sorted({r["date"] for r in rows})
    if len(days) < 2:
        raise ValueError("At least two complete observation days are required")
    cut = max(1, min(len(days)-1, int(len(days)*train_fraction)))
    train_days, test_days = set(days[:cut]), set(days[cut:])
    return ([r for r in rows if r["date"] in train_days],
            [r for r in rows if r["date"] in test_days], train_days, test_days)


def metrics(pairs):
    if not pairs: return {"n": 0}
    errors = [actual-pred for actual,pred in pairs]
    absolute = sorted(abs(e) for e in errors)
    med = sorted(errors)[len(errors)//2] if len(errors)%2 else (sorted(errors)[len(errors)//2-1]+sorted(errors)[len(errors)//2])/2
    return {"n":len(pairs), "mae_min":sum(absolute)/len(absolute),
            "rmse_min":math.sqrt(sum(e*e for e in errors)/len(errors)),
            "within_2_min_pct":100*sum(abs(e)<=2 for e in errors)/len(errors),
            "within_5_min_pct":100*sum(abs(e)<=5 for e in errors)/len(errors),
            "median_signed_error_min":med}


def evaluate(rows):
    train, test, train_days, test_days = split_days(rows)
    # Fit y ~= a + b*x on training days only (ordinary least squares).
    xs=[float(r["fifo_prediction_min"]) for r in train]; ys=[float(r["actual_wait_min"]) for r in train]
    xm=sum(xs)/len(xs); ym=sum(ys)/len(ys)
    denom=sum((x-xm)**2 for x in xs)
    b=sum((x-xm)*(y-ym) for x,y in zip(xs,ys))/denom if denom else 0.0
    a=ym-b*xm
    residuals=sorted(abs(y-(a+b*x)) for x,y in zip(xs,ys))
    # Nearest-rank 80% calibration range, based on training residuals only.
    radius=residuals[max(0, math.ceil(.8*len(residuals))-1)]
    predictions=[]
    for r in test:
        actual=float(r["actual_wait_min"]); fifo=float(r["fifo_prediction_min"])
        predictions.append({**r, "constant_2_prediction_min":2.0,
            "fifo_prediction_min":fifo, "calibrated_prediction_min":max(0.0,a+b*fifo),
            "constant_2_error_min":actual-2.0,"fifo_error_min":actual-fifo,
            "calibrated_error_min":actual-max(0.0,a+b*fifo),
            "interval_low_min":max(0.0,a+b*fifo-radius),
            "interval_high_min":max(0.0,a+b*fifo+radius)})
    summary={"train_days":sorted(train_days),"test_days":sorted(test_days),
             "calibration":{"intercept_min":a,"slope":b,"80pct_radius_min":radius},"models":{}}
    for name,predcol in (("constant_2","constant_2_prediction_min"),("fifo","fifo_prediction_min"),("calibrated","calibrated_prediction_min")):
        pairs=[(float(r["actual_wait_min"]),float(r[predcol])) for r in predictions]
        summary["models"][name]=metrics(pairs)
        groups=defaultdict(list); byday=defaultdict(list)
        for r in predictions:
            q=int(r["people_ahead"]); group="0" if q==0 else "1-4" if q<=4 else "5-9" if q<=9 else "10+"
            groups[group].append((float(r["actual_wait_min"]),float(r[predcol])))
            byday[r["date"]].append((float(r["actual_wait_min"]),float(r[predcol])))
        summary["models"][name]["mae_by_queue_group_min"]={g:metrics(v)["mae_min"] for g,v in groups.items()}
        summary["models"][name]["mae_by_test_day_min"]={d:metrics(v)["mae_min"] for d,v in byday.items()}
    cover=sum(float(r["interval_low_min"])<=float(r["actual_wait_min"])<=float(r["interval_high_min"]) for r in predictions)
    summary["prediction_interval"]={"nominal_coverage_pct":80,"test_coverage_pct":100*cover/len(predictions) if predictions else 0,"n":len(predictions)}
    return summary,predictions


def main():
    p=argparse.ArgumentParser(); p.add_argument("input"); p.add_argument("--predictions",default="reports/per_ticket_predictions.csv"); p.add_argument("--summary",default="reports/evaluation_summary.json"); a=p.parse_args()
    with open(a.input,encoding="utf-8-sig",newline="") as f: rows=list(csv.DictReader(f))
    rows=[r for r in rows if (r.get("duration_valid","true").lower()=="true") and r.get("actual_wait_min") and r.get("fifo_prediction_min") and r.get("people_ahead")]
    summary,preds=evaluate(rows)
    Path(a.predictions).parent.mkdir(parents=True,exist_ok=True)
    with open(a.predictions,"w",encoding="utf-8",newline="") as f:
        w=csv.DictWriter(f,fieldnames=list(preds[0]) if preds else []); w.writeheader(); w.writerows(preds)
    Path(a.summary).write_text(json.dumps(summary,indent=2),encoding="utf-8")
    print(json.dumps(summary,indent=2))

if __name__=="__main__": main()
